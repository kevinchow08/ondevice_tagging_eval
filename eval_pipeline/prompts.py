    "3. 数字、金额、日期这类信息要如实按文档原文摘录，不要自己简化、改写位数或四舍五入；\n"
    "4. 不确定的内容不要瞎猜；\n"
    "5. 严格只输出如下 JSON，不要输出任何其他文字：\n"
