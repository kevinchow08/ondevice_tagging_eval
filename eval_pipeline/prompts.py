    "要求：\n"
    "1. document_type 是这份文档的类型（如：发票、合同、简历、会议纪要、产品规格书、新闻报道等），只给一个最贴切的；\n"
    "2. tags 是从文档中提取出的关键实体或主题词，尽量覆盖不同类别，不要漏掉容易被忽略的结构化信息，"
    "包括但不限于：公司名/人名、金额、日期、编号类字段（发票号/合同编号/税号等，如果文档里有的话）、"
